const {test,expect}=require('@playwright/test');
test('Inteligência Executiva 1746 carrega cubos, alertas e filtros sem erros',async ({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const response=await page.goto('http://127.0.0.1:8765/1746-resumo-executivo/',{waitUntil:'load',timeout:45000});
 expect(response.status()).toBe(200);
 await expect(page.locator('#kpis .card')).toHaveCount(2);
 await expect(page.locator('#kpis')).toContainText('24.116');
 await expect(page.locator('#kpis')).toContainText('2.213');
 await expect(page.locator('#accumulated')).toContainText('278.888');
 await page.locator('#diagnostico + details').evaluate(el=>el.open=true);
 await page.locator('#composicao details').evaluate(el=>el.open=true);
 await expect(page.locator('#origin tbody tr').first()).toBeVisible();
 await expect(page.locator('#alerts button[data-alert-index]').first()).toBeVisible();
 const firstAlert=page.locator('#alerts button[data-alert-index]').first();
 await firstAlert.click();
 await expect(firstAlert).toHaveAttribute('aria-expanded','true');
 await expect(page.locator('#alertDetail')).toBeVisible();
 await expect(page.locator('#detailContent .detail-metric')).toHaveCount(2);
 await expect(page.locator('#alertCascadeServices .cascade-service').first()).toBeVisible();
 await expect(page.locator('#alertCascade')).toContainText('De onde vêm os registros');
 await page.locator('#alertCascadeServices [data-service-index]').first().click();
 await expect(page.locator('#alertCascadeServices [data-service-body="0"]')).toBeVisible();
 await expect(page.locator('#alertCascadeServices [data-sub-index]').first()).toBeVisible();
 await page.locator('#alertCascadeServices [data-sub-index]').first().click();
 await expect(page.locator('#alertCascadeServices .cascade-territory:visible').first()).toContainText('Subtipo:');
 await expect(page.locator('#detailContent')).toContainText('Out/2025');
 const selectedTitle=await page.locator('#alerts button[data-alert-index]').first().locator('h3').innerText();
 await expect(page.locator('#detailTitle')).toContainText(selectedTitle.split('·')[0].trim());
 await page.locator('#detailClose').click();
 await expect(page.locator('#alertDetail')).toBeHidden();
 await expect(firstAlert).toHaveAttribute('aria-expanded','false');
 await page.locator('#territorio details').first().evaluate(el=>el.open=true);
 await expect(page.locator('#aps tbody tr').first()).toBeVisible();
 await page.locator('#scope').selectOption('accumulated');
 await expect(page.locator('#origin')).toContainText('Saldo líquido');
 await page.locator('#metric').selectOption('o');
 await expect(page.locator('#subtypes tbody tr').first()).toBeVisible();
 await page.locator('#trendMetric').selectOption('o');
 await page.locator('#sintese details').first().evaluate(el=>el.open=true);
 await expect(page.locator('#trend .chartrow')).toHaveCount(10);
 await page.screenshot({path:info.outputPath('executivo-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:info.outputPath('executivo-mobile.png'),fullPage:true});
 const over=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 expect(over).toBeLessThan(26);
 expect(errors).toEqual([]);
});